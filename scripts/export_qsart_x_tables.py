"""Export IEEE manuscript tables and figure includes from audited study reports."""

import argparse
from hashlib import sha256
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'docs' / 'research' / 'QSART_X_TABLES.tex'
PAIRED_LABELS = {
    'first_view': 'First view only', 'voi': 'Estimated-value ranking',
    'voi_positive': 'Estimated value above cost', 'both_views': 'Both recorded views',
}


def audited(study):
    folder = ROOT / 'reports' / study
    payload = (folder / 'evaluation.json').read_bytes()
    result = json.loads(payload)
    receipt = json.loads((folder / 'independent_audit.json').read_bytes())
    digest = sha256(payload).hexdigest()
    if (receipt['audit_status'] != 'passed' or receipt['evaluation_sha256'] != digest
            or result['experiment_id'] != study or receipt['experiment_id'] != study
            or receipt['source_commit'] != result['source_commit']
            or receipt['private_witness_sha256'] != result['private_witness_sha256']):
        raise ValueError(f'{study} does not match its independent audit')
    return result, digest


def table(caption, label, columns, headings, rows):
    return [r'\begin{table*}[t]', r'\centering', rf'\caption{{{caption}}}', rf'\label{{{label}}}',
            rf'\begin{{tabular}}{{{columns}}}', r'\hline', ' & '.join(headings) + r' \\', r'\hline',
            *(' & '.join(map(str, row)) + r' \\' for row in rows), r'\hline', r'\end{tabular}', r'\end{table*}', '']


def figure(path, caption, label):
    if not (ROOT / path).is_file():
        raise FileNotFoundError(f'Missing manuscript figure: {path}')
    return [r'\begin{figure*}[t]', r'\centering', rf'\includegraphics[width=\textwidth]{{{path}}}',
            rf'\caption{{{caption}}}', rf'\label{{{label}}}', r'\end{figure*}', '']


def render():
    set_c, set_c_hash = audited('set_c_validation_v1')
    paired, paired_hash = audited('paired_view_v1')
    set_c_rows = []
    for row in set_c['scenarios']:
        if row['mode'] != 'ordinal' or row['method'] != 'dual_budget':
            continue
        review, recapture = (f'{value:.0%}'.replace('%', r'\%') for value in row['budget'])
        outcomes = row['outcomes']
        if outcomes is None:
            set_c_rows.append((f'{review} / {recapture}', 'Overload', '--', '--'))
        else:
            actions = outcomes['patient_actions']
            set_c_rows.append((f'{review} / {recapture}', 'Evaluated', actions['SPECIALIST_REVIEW'],
                               actions['AUTO_NONREFERABLE']))

    paired_rows = []
    for row in paired['scenarios']:
        if row['method'] not in PAIRED_LABELS or (row['method'] == 'voi_positive' and row['budget'] != .10):
            continue
        outcomes = row['outcomes']
        paired_rows.append((PAIRED_LABELS[row['method']], outcomes['extra_views'], outcomes['referable_misses'],
                            outcomes['severe_misses'], f"{outcomes['ledger_per_eye']:.4f}"))

    return '\n'.join([
        '% Generated by scripts/export_qsart_x_tables.py. Compile from the repository root with graphicx.',
        f'% Set-C evaluation SHA-256: {set_c_hash}', f'% Paired-view evaluation SHA-256: {paired_hash}', '',
        *table('Deployed ordinal dual-budget policy on DeepDRiD Set-C (99 patients).', 'tab:qsart-set-c', 'llrr',
               ('Image caps', 'Status', 'Review', 'Automatic'), set_c_rows),
        *table('Retrospective paired-view acquisition on 84 eyes. Misses count eye-level missed referrals.',
               'tab:qsart-paired-views', 'lrrrr', ('Policy', 'Views', 'Misses', 'Severe', 'Cost/eye'), paired_rows),
        *figure('reports/set_c_validation_v1/patient_dispositions.png',
                'Patient recommendations under the deployed ordinal gate and two diagnostic variants.',
                'fig:qsart-set-c'),
        *figure('reports/paired_view_v1/acquisition_workload.png',
                'Research ledger by the number of additional recorded views.', 'fig:qsart-paired-views'),
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify the checked-in export instead of writing it')
    args = parser.parse_args()
    output = render().encode('utf-8')
    if args.check:
        if OUTPUT.read_bytes() != output:
            parser.error('The IEEE table export differs from the audited reports')
        print('IEEE manuscript table export matches the audited reports.')
    else:
        OUTPUT.write_bytes(output)


if __name__ == '__main__':
    main()
