def parquet(tmp_path,names,grades=None):
    grades=grades or [0]*len(names)
    table=pa.table({'image':pa.array([{'bytes':b'not a JPEG; must not be decoded','path':name} for name in names],
        type=pa.struct([('bytes',pa.binary()),('path',pa.string())])),
        'label_code':grades,'label':[hf.LABELS[g] for g in grades]})
    p=hf.cache_path(tmp_path,record()['path']);p.parent.mkdir(parents=True)
    pq.write_table(table,p)
    return {'files':[{'path':record()['path'],'bytes':p.stat().st_size,'sha256':hf.sha256(p)}],'expected_rows':len(names)}


def test_parquet_metadata_projection_does_not_decode_embedded_image_bytes(tmp_path):
    manifest=parquet(tmp_path,['1_left.jpeg','2_right.jpeg'],[0,2])
    frame=hf.read_metadata(tmp_path,manifest)
    assert frame.original_image_name.tolist()==['1_left.jpeg','2_right.jpeg']
    assert frame.mirror_dr_grade.tolist()==[0,2] and 'image' not in frame


