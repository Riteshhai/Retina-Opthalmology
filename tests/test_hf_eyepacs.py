def test_download_verifies_then_reuses_cache_without_network_or_overwrite(tmp_path):
    data=b'generated bytes, not an image';r=record(data);calls=[]
    def handler(request):calls.append(request);return response(200,data,**{'content-length':str(len(data))})
    with httpx.Client(transport=httpx.MockTransport(handler)) as client:
        assert hf.download_record(r,tmp_path,client=client)['already_cached'] is False
        assert hf.download_record(r,tmp_path,client=client)['already_cached'] is True
        assert len(calls)==1
        p=tmp_path/r['path'];p.write_bytes(b'changed local bytes')
        with pytest.raises(ValueError,match='Existing cached'):hf.download_record(r,tmp_path,client=client)
        assert p.read_bytes()==b'changed local bytes' and len(calls)==1


def partial(tmp_path,data,amount):
    r=record(data);p=hf.cache_path(tmp_path,r['path']);p.parent.mkdir(parents=True)
    part=p.with_suffix(p.suffix+'.part');part.write_bytes(data[:amount])
    marker=part.with_suffix(part.suffix+'.json')
    marker.write_text(json.dumps({'repository':hf.REPOSITORY,'revision':hf.REVISION,**r}))
    return r,p,part,marker


def test_interrupted_transfer_resumes_exact_range_and_keeps_existing_prefix(tmp_path):
    data=b'0123456789';r,p,part,_=partial(tmp_path,data,4)
    def handler(request):
        assert request.headers['range']=='bytes=4-'
        return response(206,data[4:],**{'content-range':'bytes 4-9/10','content-length':'6'})
    with httpx.Client(transport=httpx.MockTransport(handler)) as client:hf.download_record(r,tmp_path,client=client)
    assert p.read_bytes()==data and not part.exists()


@pytest.mark.parametrize('failure',['range_ignored','range_wrong','marker_wrong','marker_missing','checksum'])
def test_partial_mismatch_is_preserved_and_never_promoted(tmp_path,failure):
    data=b'0123456789';r,p,part,marker=partial(tmp_path,data,4)
    if failure=='marker_wrong':marker.write_text('{}')
    if failure=='marker_missing':marker.unlink()
    def handler(request):
        if failure=='range_ignored':return response(200,data)
        start=3 if failure=='range_wrong' else 4
        return response(206,b'xxxxxx' if failure=='checksum' else data[4:],**{'content-range':f'bytes {start}-9/10','content-length':'6'})
    with httpx.Client(transport=httpx.MockTransport(handler)) as client:
        with pytest.raises(ValueError):hf.download_record(r,tmp_path,client=client)
    assert part.exists() and not p.exists()
    assert part.read_bytes().startswith(data[:4])


