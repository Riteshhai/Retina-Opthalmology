def test_quality_join_retains_three_classes_missingness_and_transformed_source(monkeypatch):
    source=pd.DataFrame({'original_image_name':['1_left.jpeg','2_right.jpeg','3_left.jpeg'],
        'eyeq_quality_code':[0,1,2],'source_dr_grade':[0,2,4]})
    monkeypatch.setattr(hf,'load_annotations',lambda _:source)
    frame=pd.DataFrame({'original_image_name':['1_left.jpeg','2_right.jpeg'],'mirror_dr_grade':[0,2]})
    joined,summary=hf.annotation_join(frame,'generated_fixture')
    assert summary['matched_quality_counts']=={'0':1,'1':1,'2':0}
    assert summary['missing_quality_counts']=={'0':0,'1':0,'2':1}
    assert summary['ready_for_model_evaluation'] is False and summary['eligible_for_training'] is False
    assert summary['quality_annotations_revalidated_after_transform'] is False
    assert not {'dr_grade','quality_grade'}.intersection(joined)
    frame.loc[0,'mirror_dr_grade']=3
    with pytest.raises(ValueError,match='conflict'):hf.annotation_join(frame,'generated_fixture')
