def record(data=b'generated transfer fixture'):
    return {'path':'data/train-00000-of-00014.parquet','bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()}


def response(status,data=b'',**headers):return httpx.Response(status,stream=httpx.ByteStream(data),headers=headers)


def test_manifest_is_bound_to_selected_repo_revision_all_shards_and_sizes():
    manifest=json.loads((Path(__file__).resolve().parents[1]/'configs/eyepacs_hf_v1.json').read_text(encoding='utf-8'))
    assert hf.validate_manifest(manifest)==manifest
    for field,value in [('repository','unverified/replacement'),('revision','main'),('total_bytes',1),
        ('card_sha256','a'*64),('files',manifest['files'][:-1]),('expected_rows',35126)]:
        changed=deepcopy(manifest);changed[field]=value
        with pytest.raises(ValueError):hf.validate_manifest(changed)


